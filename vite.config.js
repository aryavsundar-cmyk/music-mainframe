/**
 * Folders whose every module is authored. Nothing under one may enter a work bundle, whether or not it is named
 * in WORK_SWAPS — `cases/index.js` is swapped, but a future page importing `cases/halcyon.js` directly would
 * route around that swap, and the swap list would still look complete.
 *
 * (The word "folders" rather than the obvious one: `export-edition.mjs` greps every copied file for private
 * strings as a plain substring match, and this file is copied. That grep should stay blunt — a looser one is a
 * worse check — so prose here works around it rather than the other way about.)
 */
export const WORK_PRIVATE_DIRS = [
  'src/data/cases/',
  'src/components/consulting/',
]

/** Where the module manifest is written. OUTSIDE the out dir: a list of module paths must not ship. */
export const MANIFEST = (edition) => at(`.edition-modules.${edition}.json`)

/** The reviewed list of modules permitted in a work build. Regenerated by `npm run edition:allow`. */
export const ALLOWLIST = at('src/editions/work-allowlist.json')

/**
 * Records every module rollup actually put in the bundle, so the edition test can assert what IS there rather
 * than grepping for strings it already knows about.
 *
 * The string blocklist in `scripts/test-edition.mjs` can only catch a leak it was told to look for, and two of
 * the swapped modules (`navPrivate.js`, `gammaExport.js`) contain no distinctive string literal at all — there
 * is nothing to grep for, so no blocklist could ever protect them. A module inventory can, and it is derived
 * from WORK_SWAPS, so adding a swap adds its own test instead of relying on somebody remembering to.
 *
 * Written outside the out dir on purpose. Emitting it into `dist-work` would ship a list of this project's
 * module paths to anyone the work edition is handed to — and, if a private module ever did leak, would hand
 * them its name as well.
 */
function editionManifest(edition) {
  return {
    name: 'mm-edition-manifest',
    generateBundle(_options, bundle) {
      const modules = new Set()
      let external = 0
      for (const chunk of Object.values(bundle)) {
        for (const id of Object.keys(chunk.modules || {})) {
          const clean = id.split('?')[0]
          if (clean.includes('node_modules') || clean.startsWith('\0') || !path.isAbsolute(clean)) { external += 1; continue }
          modules.add(path.relative(dir, clean).split(path.sep).join('/'))
        }
      }
      fs.writeFileSync(MANIFEST(edition), `${JSON.stringify({
        edition,
        builtAt: new Date().toISOString(),
        external,
        modules: [...modules].sort(),
      }, null, 2)}\n`)
    },
  }
}

/**
 * Swaps the authored modules for stubs by RESOLVED path, not by import string — an alias on the specifier
 * misses every importer that spells the path differently, which is exactly how a leak gets shipped.
 */
function editionPlugin(edition) {
  if (edition !== 'work') return null
  const swaps = new Map(WORK_SWAPS.map(([from, to]) => [path.normalize(at(from)), at(to)]))
  return {
    name: 'mm-edition-swap',
    enforce: 'pre',
    async resolveId(source, importer, options) {
      if (options?.isEntry) return null
      const resolved = await this.resolve(source, importer, { ...options, skipSelf: true })
      if (!resolved) return null
      const hit = swaps.get(path.normalize(resolved.id.split('?')[0]))
      return hit || null
    },
  }
}

const edition = process.env.MM_EDITION === 'work' ? 'work' : 'full'

export default defineConfig({
  plugins: [react(), tailwindcss(), editionPlugin(edition), editionManifest(edition)].filter(Boolean),
  define: { 'import.meta.env.VITE_MM_EDITION': JSON.stringify(edition) },
  server: {
    port: 5190, host: true,
    // Live-news backend runs separately on :3002 in dev (same origin in prod).
    proxy: { '/api': 'http://localhost:3002', '/ws': { target: 'ws://localhost:3002', ws: true } },
  },
  build: {
    outDir: edition === 'work' ? 'dist-work' : 'dist',
    rollupOptions: {
      output: {
        // Keep vendor React/Router separate so future export renderers (pptxgenjs, docx)
        // can be lazy-loaded without bloating the core bundle (sibling anti-pattern #1).
        manualChunks: { vendor: ['react', 'react-dom', 'react-router-dom'] },
      },
    },
  },
})
